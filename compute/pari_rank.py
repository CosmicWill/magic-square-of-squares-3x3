"""PARI/GP rank certificates for the transparent primes, and the
general mod-p criterion (entry 79).

THE CRITERION (Rank-r Theorem).  Let p be transparent, E_n: y^2 = x^3
- n^2 x with n = |sqfree(A4)| (isomorphic over Q to y^2 = x^3 - A4^2 x
by x -> x/k^2, y -> y/k^3, k^2 = |A4|/n, p !| k).  Let G_1..G_r be
rational points such that L = <G_1..G_r> + E[2] has ODD index in E(Q)
(2-saturated).  If a solution point P_sol existed, P_sol = P0 + 2Q with
Q in E(Q); reducing mod p (P0 -> T1 = (0,0), P_sol -> O) gives
2 Q~ = T1~.  With d odd and dQ = sum a_i G_i + T:
    T1~ = d T1~ = 2d Q~ = 2 sum a_i G_i~   in   2H,  H = <G_1~..G_r~>.
So   T1~ NOT in 2H   ==>   no solution: the rigidity lemma holds at p.
For r = 1 this is automatic (the Rank-1 Theorem); for r >= 2 it is a
finite computation in E~(F_p) once generators are known.

PARI's ellrank (2-descent + Cassels-Tate) returns [r, R, s, points]
with r <= rank <= R; ellsaturation(E, pts, 2) 2-saturates.  The sweep
output (RES p n r R s [points]) is parsed here and re-verified in
exact arithmetic: points on the curve, descent-image independence,
and the half-test T1~ in 2H by brute-force subgroup closure.
"""
